"""Storage layer: SQLite persistence for habits and completions.

This is the only module that knows SQL exists. It performs CRUD against the
database defined in :mod:`habit_tracker.db` and maps rows to and from the
domain objects in :mod:`habit_tracker.models`.

Deliberately out of scope here (handled by higher layers):
  - Business rules (duplicate checks, double-completion-per-period, validity).
  - Analytics (streaks, completion rates).

The Storage class only persists and retrieves data faithfully.
"""

from __future__ import annotations

import sqlite3
from datetime import datetime

from .models import Completion, Habit


class Storage:
    """Persistence gateway for :class:`Habit` and :class:`Completion`.

    Wraps a single SQLite connection and translates between database rows and
    domain objects. The connection must already have its schema initialised
    (see :func:`habit_tracker.db.init_db`) and foreign keys enabled.

    Attributes:
        conn: The underlying open SQLite connection. The caller owns its
            lifecycle (opening and closing).
    """

    def __init__(self, conn: sqlite3.Connection) -> None:
        """Bind the storage to an open, schema-ready SQLite connection.

        Args:
            conn: An open connection whose ``row_factory`` is expected to be
                ``sqlite3.Row`` so rows support name-based access.
        """
        self.conn = conn

    # ------------------------------------------------------------------
    # Row mapping
    # ------------------------------------------------------------------
    @staticmethod
    def _row_to_habit(row: sqlite3.Row) -> Habit:
        """Convert a ``habits`` table row into a :class:`Habit`.

        Args:
            row: A row with columns ``id``, ``name``, ``description``,
                ``periodicity`` and ``created_at`` (ISO 8601 string).

        Returns:
            The reconstructed :class:`Habit`, with ``created_at`` parsed back
            into a ``datetime`` and ``id`` populated.
        """
        return Habit(
            id=row["id"],
            name=row["name"],
            description=row["description"],
            periodicity=row["periodicity"],
            created_at=datetime.fromisoformat(row["created_at"]),
        )

    @staticmethod
    def _row_to_completion(row: sqlite3.Row) -> Completion:
        """Convert a ``completions`` table row into a :class:`Completion`.

        Args:
            row: A row with columns ``id``, ``habit_id`` and ``completed_at``
                (ISO 8601 string).

        Returns:
            The reconstructed :class:`Completion`, with ``completed_at`` parsed
            back into a ``datetime`` and ``id`` populated.
        """
        return Completion(
            id=row["id"],
            habit_id=row["habit_id"],
            completed_at=datetime.fromisoformat(row["completed_at"]),
        )

    # ------------------------------------------------------------------
    # Habit CRUD
    # ------------------------------------------------------------------
    def add_habit(self, habit: Habit) -> Habit:
        """Insert a habit and return it with its database id populated.

        Args:
            habit: The habit to persist. Its ``id`` is ignored on input; the
                stored ``name``, ``description``, ``periodicity`` and
                ``created_at`` (serialised to ISO 8601) are written.

        Returns:
            A new :class:`Habit` identical to the input but with ``id`` set to
            the autogenerated primary key.
        """
        cursor = self.conn.execute(
            "INSERT INTO habits (name, description, periodicity, created_at) "
            "VALUES (?, ?, ?, ?)",
            (
                habit.name,
                habit.description,
                habit.periodicity,
                habit.created_at.isoformat(),
            ),
        )
        self.conn.commit()
        return Habit(
            id=cursor.lastrowid,
            name=habit.name,
            description=habit.description,
            periodicity=habit.periodicity,
            created_at=habit.created_at,
        )

    def remove_habit(self, habit_id: int) -> None:
        """Delete a habit by id.

        Thanks to the ``ON DELETE CASCADE`` foreign key, the habit's
        completions are removed with it. Deleting a non-existent id is a no-op.

        Args:
            habit_id: Primary key of the habit to delete.
        """
        self.conn.execute("DELETE FROM habits WHERE id = ?", (habit_id,))
        self.conn.commit()

    def get_habit_by_name(self, name: str) -> Habit | None:
        """Fetch a single habit by its unique name.

        Args:
            name: The habit name to look up.

        Returns:
            The matching :class:`Habit`, or ``None`` if no habit has that name.
        """
        row = self.conn.execute(
            "SELECT id, name, description, periodicity, created_at "
            "FROM habits WHERE name = ?",
            (name,),
        ).fetchone()
        return self._row_to_habit(row) if row is not None else None

    def get_all_habits(self) -> list[Habit]:
        """Fetch every stored habit.

        Returns:
            A list of all :class:`Habit` objects, ordered by id. Empty if no
            habits are stored.
        """
        rows = self.conn.execute(
            "SELECT id, name, description, periodicity, created_at "
            "FROM habits ORDER BY id"
        ).fetchall()
        return [self._row_to_habit(row) for row in rows]

    # ------------------------------------------------------------------
    # Completion CRUD
    # ------------------------------------------------------------------
    def add_completion(
        self, habit_id: int, when: datetime | None = None
    ) -> Completion:
        """Record a completion for a habit and return it with its id.

        Args:
            habit_id: The id of the habit being completed.
            when: Timestamp of the completion. Defaults to the current local
                time when omitted.

        Returns:
            The persisted :class:`Completion` with ``id`` populated.
        """
        completed_at = when if when is not None else datetime.now()
        cursor = self.conn.execute(
            "INSERT INTO completions (habit_id, completed_at) VALUES (?, ?)",
            (habit_id, completed_at.isoformat()),
        )
        self.conn.commit()
        return Completion(
            id=cursor.lastrowid,
            habit_id=habit_id,
            completed_at=completed_at,
        )

    def get_completions(self, habit_id: int) -> list[Completion]:
        """Fetch all completions for a habit, oldest first.

        Args:
            habit_id: The id of the habit whose completions to retrieve.

        Returns:
            A list of :class:`Completion` objects ordered by ``completed_at``
            ascending. Empty if the habit has no completions.
        """
        rows = self.conn.execute(
            "SELECT id, habit_id, completed_at FROM completions "
            "WHERE habit_id = ? ORDER BY completed_at ASC",
            (habit_id,),
        ).fetchall()
        return [self._row_to_completion(row) for row in rows]
